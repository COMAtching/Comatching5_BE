"""Generate reproducible local fixtures. Never imports a database client."""
import argparse
import csv
import json
import os
import random
import re
import shutil
import tempfile
from collections import Counter
from datetime import date, datetime, time, timedelta
from pathlib import Path

import bcrypt
from model import (ROOT, VERSION, TABLES, COLLECTIONS, SCENARIOS, MBTIS, CONTACTS,
                   MAJORS, columns, digest, korean_age)

def uniform(values, n, seed):
    result = [values[i % len(values)] for i in range(n)]
    random.Random(seed).shuffle(result)
    return result

def birth_for_age(age, today, rng):
    month, day = rng.randint(1, 12), rng.randint(1, 28)
    year = today.year - age + 1 - ((month, day) > (today.month, today.day))
    birth = date(year, month, day)
    assert korean_age(birth, today) == age
    return birth.isoformat()

def domains():
    folder = ROOT / 'common-module/src/main/java/com/comatching/common/domain/enums'
    hobby_text = (folder / 'DefaultHobby.java').read_text()
    hobbies = re.findall(r'^\s*([A-Z][A-Z0-9_]*)\(HobbyCategory\.([A-Z]+),', hobby_text, re.M)
    tags = re.findall(r'^\s*([A-Z][A-Z0-9_]*)\([A-Z_]+,', (folder/'ProfileTagItem.java').read_text(), re.M)
    if not hobbies or not tags:
        raise ValueError('Could not read application enum definitions')
    return hobbies, tags

class Writer:
    def __init__(self, directory):
        self.directory = directory
        self.files, self.writers, self.counts = {}, {}, Counter()
        for table in TABLES:
            f = open(directory / (table+'.tsv'), 'w', newline='', encoding='utf-8')
            self.files[table] = f
            self.writers[table] = csv.writer(f, delimiter='\t', lineterminator='\n')
            self.writers[table].writerow(columns(table))
        for c in COLLECTIONS:
            self.files[c] = open(directory/(c+'.jsonl'), 'w', encoding='utf-8')

    def row(self, table, **data):
        if set(data) != set(columns(table)):
            raise ValueError(f'{table}: bad columns {set(data) ^ set(columns(table))}')
        self.writers[table].writerow(['\\N' if data[c] is None else data[c] for c in columns(table)])
        self.counts[table] += 1

    def doc(self, collection, data):
        self.files[collection].write(json.dumps(data, ensure_ascii=False, separators=(',', ':'))+'\n')
        self.counts[collection] += 1

    def close(self):
        for f in self.files.values():
            f.close()

def generate(out, *, count=100000, scenario_count=1000, vu_accounts=500,
             start_id=1000001, seed=20261118, as_of='2026-11-18', distribution='uniform',
             password='LocalSeed!2026', dataset='local-100k', history_count=None,
             order_count=None, roulette_count=None, messages_per_room=20,
             at='12:00:00', preset='baseline'):
    out = Path(out).resolve()
    if count < 20 or not 0 <= scenario_count < count or not 1 <= vu_accounts <= count-scenario_count:
        raise ValueError('count >= 20; 0 <= scenarios < count; 1 <= VU <= normal members required')
    if not 1 <= start_id <= 10**12 or not re.fullmatch(r'[a-z0-9][a-z0-9-]{0,47}', dataset):
        raise ValueError('Invalid start ID or dataset name')
    if distribution not in ('uniform', 'skewed') or messages_per_room < 1:
        raise ValueError('Invalid distribution or message count')
    if preset not in ('baseline','no-candidates'):
        raise ValueError('Invalid preset')
    if preset=='no-candidates' and (vu_accounts!=1 or history_count not in (None,0)):
        raise ValueError('no-candidates requires --vu-accounts 1 and no matching history')
    if out.exists():
        raise ValueError(f'Output already exists; use a new directory: {out}')
    today = date.fromisoformat(as_of)
    now = datetime.combine(today, time.fromisoformat(at))
    stamp = lambda dt: dt.strftime('%Y-%m-%d %H:%M:%S')
    mongo_time = lambda dt: {'$date': dt.isoformat()+'+09:00'}
    rng = random.Random(seed)
    hobbies, tags = domains()
    # Fixed test-only salt makes all generated bytes reproducible. Never production credentials.
    hashed = bcrypt.hashpw(password.encode(), b'$2b$10$......................').decode()
    n = count - scenario_count
    genders = uniform(['MALE', 'FEMALE'], n, seed+1)
    ages = uniform(list(range(20, 28)), n, seed+2)
    mbtis = uniform(MBTIS, n, seed+3)
    majors = uniform(MAJORS, n, seed+4)
    contacts = uniform(CONTACTS, n, seed+5)
    if distribution == 'skewed':
        genders = uniform(['MALE']*8+['FEMALE']*2, n, seed+1)
        majors = uniform([MAJORS[0]]*70 + MAJORS[1:]*2, n, seed+4)
    out.parent.mkdir(parents=True, exist_ok=True)
    temp = Path(tempfile.mkdtemp(prefix='.generating-', dir=out.parent))
    w = Writer(temp)
    accounts, examples, male, female, active = [], {}, [], [], []
    distribution_counts = {k: Counter() for k in ('gender', 'age', 'mbti', 'major', 'contact_frequency', 'scenario', 'random_key_decile')}
    next_ids = Counter()
    def new_id(table):
        next_ids[table] += 1
        return start_id * 100 + next_ids[table]
    def item(mid, typ, quantity, expiration, history_type='EVENT', description='로컬 테스트 초기 지급'):
        w.row('item', id=new_id('item'), member_id=mid, item_type=typ, quantity=quantity, expired_at=stamp(expiration))
        w.row('item_history', id=new_id('item_history'), member_id=mid, item_type=typ,
              history_type=history_type, quantity=quantity, description=description, created_at=stamp(now))
    try:
        for i in range(count):
            mid = start_id+i
            case = SCENARIOS[(i*len(SCENARIOS))//scenario_count] if i < scenario_count else 'bulk'
            role = {'guest': 'ROLE_GUEST', 'admin': 'ROLE_ADMIN'}.get(case, 'ROLE_USER')
            status = case.upper() if case in ('pending','dormant','suspended','banned','withdrawn') else 'ACTIVE'
            gender = ['MALE','FEMALE'][i % 2] if i < scenario_count else genders[i-scenario_count]
            age = int(case[4:]) if case.startswith('age_') else (24 if i < scenario_count else ages[i-scenario_count])
            mbti = MBTIS[i % 16] if i < scenario_count else mbtis[i-scenario_count]
            major = MAJORS[i % len(MAJORS)] if i < scenario_count else majors[i-scenario_count]
            contact = CONTACTS[i % 3] if i < scenario_count else contacts[i-scenario_count]
            nickname = f'테스트{mid}'
            email = f'{dataset}.{mid}@example.test'
            withdrawn = status == 'WITHDRAWN'
            vu = scenario_count <= i < scenario_count+vu_accounts
            w.row('members', member_id=mid, email=email, password=None if withdrawn else hashed,
                  real_name=f'테스트{mid}', social_id=None, role=role, social_type=None if withdrawn else 'LOCAL',
                  status=status, deleted_at=stamp(now-timedelta(days=1)) if withdrawn else None)
            accounts.append([mid, email, nickname if role == 'ROLE_USER' else '', case, role, status, int(vu)])
            examples.setdefault(case, []).append(mid)
            distribution_counts['scenario'][case] += 1
            if role in ('ROLE_GUEST', 'ROLE_ADMIN'):
                continue
            matchable = int(status == 'ACTIVE' and case != 'not_matchable')
            if preset=='no-candidates': matchable=int(i==scenario_count)
            chosen_hobbies = rng.sample(hobbies, 2 if case == 'minimal_profile' else (5 if case == 'rich_profile' else 3))
            chosen_tags = [] if case == 'minimal_profile' else rng.sample(tags, 5 if case == 'rich_profile' else 3)
            birth = birth_for_age(age, today, rng)
            if withdrawn:
                nickname, birth, mbti, major = '탈퇴한 사용자', '1970-01-01', 'UNKNOWN', '(알 수 없음)'
                chosen_hobbies, chosen_tags = [], []
                accounts[-1][2] = nickname
            w.row('profile', profile_id=mid, member_id=mid, birth_date=birth, point=0,
                  intro=None if withdrawn or case == 'minimal_profile' else '함께 산책하고 취미 이야기를 나누고 싶어요.',
                  major=major, mbti=mbti, nickname=nickname,
                  profile_image_url=None,
                  social_account_id=None if withdrawn or case=='minimal_profile' else f'seed_{mid}', song=None,
                  university='(알 수 없음)' if withdrawn else '가톨릭대학교', contact_frequency=contact,
                  gender=gender, social_account_type=None if withdrawn or case=='minimal_profile' else 'INSTAGRAM',
                  is_matchable=matchable)
            for hobby, category in chosen_hobbies:
                w.row('profile_hobby', id=new_id('profile_hobby'), profile_id=mid, name=hobby, category=category)
            for tag in chosen_tags:
                w.row('profile_tag', id=new_id('profile_tag'), profile_id=mid, tag=tag)
            if withdrawn:
                w.row('withdrawn_member', member_id=mid, withdrawn_at=stamp(now-timedelta(days=1)))
                continue
            random_key = rng.randrange(1000000000)
            w.row('matching_candidate', member_id=mid, profile_id=mid, age=age, gender=gender,
                  contact_frequency=contact, major=major, mbti=mbti, is_matchable=matchable, random_key=random_key)
            for _, category in chosen_hobbies:
                w.row('candidate_hobby_categories', member_id=mid, hobby_categories=category)
            for key, value in [('gender',gender),('age',age),('mbti',mbti),('major',major),
                               ('contact_frequency',contact),('random_key_decile',random_key//100000000)]:
                distribution_counts[key][value] += 1
            if case == 'bulk' and not vu:
                (male if gender == 'MALE' else female).append(mid)
                active.append(mid)
            if status != 'ACTIVE' or case == 'no_items':
                continue
            matching, options = (2000,6000) if vu else (10,30)
            expiration = now+timedelta(days=365)
            if case == 'zero_items': matching, options = 0,0
            if case == 'one_ticket': matching, options = 1,0
            if case == 'no_options': options = 0
            if case == 'expired_items': expiration = now-timedelta(days=1)
            if case == 'expiring_items': expiration = now+timedelta(hours=1)
            item(mid, 'MATCHING_TICKET', matching, expiration)
            item(mid, 'OPTION_TICKET', options, expiration)

        # Disjoint male/female pairs; VU accounts keep a clean matching history.
        rng.shuffle(male); rng.shuffle(female)
        limit = min(len(male),len(female))
        histories = min(count//10, limit) if history_count is None else history_count
        if preset=='no-candidates': histories=0
        if not 0 <= histories <= limit:
            raise ValueError(f'history_count must be 0..{limit}')
        for i, (a,b) in enumerate(zip(male[:histories],female[:histories])):
            hid = new_id('matching_history')
            ts = now-timedelta(days=1, minutes=histories-i)
            w.row('matching_history', id=hid, member_id=a, partner_id=b, pair_key=f'{min(a,b)}:{max(a,b)}',
                  favorite=int(i%3 == 0), matched_at=stamp(ts), same_major_option=0, age_option=None,
                  min_age_offset=None, max_age_offset=None, contact_frequency=None,
                  hobby_option=None, mbti_option=None, important_option=None)
            rid = f'seed-{dataset}-room-{hid}' # Non-ObjectId string: Spring keeps it as a string.
            waiting = i%5 == 0
            sent = ts+timedelta(seconds=messages_per_room)
            w.doc('chat_rooms', {'_id':rid, 'matchingId':hid, 'initiatorUserId':a, 'targetUserId':b,
                  'status':'WAITING' if waiting else 'ACTIVE',
                  'lastMessageInfo':None if waiting else {'content':f'테스트 대화 {messages_per_room}', 'sentAt':mongo_time(sent)},
                  'initiatorLastReadAt':mongo_time(ts), 'targetLastReadAt':mongo_time(ts),
                  'createdAt':mongo_time(ts), 'updatedAt':mongo_time(ts if waiting else sent)})
            if not waiting:
                for j in range(1,messages_per_room+1):
                    w.doc('chat_messages', {'_id':f'{rid}-message-{j}', 'roomId':rid,
                          'senderId':a if j%2 else b, 'content':f'테스트 대화 {j}', 'type':'TALK',
                          'createdAt':mongo_time(ts+timedelta(seconds=j))})
            if i%100 == 0:
                w.doc('user_blocks', {'_id':f'seed-{dataset}-block-{hid}', 'blockerUserId':a,
                      'blockedUserId':b, 'createdAt':mongo_time(now)})

        orders = min(count//10,len(active)) if order_count is None else order_count
        roulettes = min(count//100,len(active)) if roulette_count is None else roulette_count
        if not 0 <= orders <= len(active) or not 0 <= roulettes <= len(active):
            raise ValueError('Orders/roulette exceed available normal members')
        refs = {'products': {}, 'rewards': {}}
        for i,mid in enumerate(active[:orders]):
            oid, iid = new_id('purchase_order'), new_id('purchase_order_item')
            state = ['PENDING','APPROVED','REJECTED','CANCELED','EXPIRED'][i%5]
            decision = stamp(now-timedelta(hours=1)) if state != 'PENDING' else None
            refs['products'][str(oid)] = 'MATCHING_TICKET_1'
            w.row('purchase_order', id=oid, member_id=mid, product_id=None, product_code='MATCHING_TICKET_1',
                  requested_item_name='뽑기권 1장', requester_real_name=f'테스트{mid}', requester_username=f'테스트{mid}',
                  requested_price=1000, expected_price=1000, status=state,
                  requested_at=stamp(now-timedelta(days=2)),
                  expires_at=stamp(now-timedelta(hours=2) if state == 'EXPIRED' else now+timedelta(days=7)),
                  decided_at=decision)
            w.row('purchase_order_item', id=iid, order_id=oid, item_type='MATCHING_TICKET', quantity=1)
            if decision:
                w.row('order_decision_logs', id=new_id('order_decision_logs'), order_id=oid,
                      from_status='PENDING', to_status=state, decided_by_admin_id=None,
                      reason='로컬 테스트 상태 이력', decided_at=decision, created_at=decision, updated_at=decision)
            if state == 'APPROVED':
                w.row('order_grant_ledger', id=new_id('order_grant_ledger'), order_id=oid, order_item_id=iid,
                      member_id=mid, item_type='MATCHING_TICKET', quantity=1, granted_at=decision,
                      created_at=decision, updated_at=decision)
                item(mid, 'MATCHING_TICKET', 1, now+timedelta(days=365), 'CHARGE', '로컬 테스트 주문 지급')
        for i,mid in enumerate(active[:roulettes]):
            rid = new_id('roulette_history')
            special = i%2 == 1
            typ = 'SPECIAL' if special else 'FREE'
            refs['rewards'][str(rid)] = {'roulette_type':typ, 'reward_type':'GIFT_CARD' if special else 'NONE',
                                        'reward_name':'1만원권 상품권' if special else '꽝', 'quantity':0}
            w.row('roulette_history', id=rid, member_id=mid, reward_id=None, roulette_type=typ,
                  participated_at=stamp(now), participation_date=as_of, reward_granted=int(not special))
        w.close()
        for filename, rows, header in [
            ('accounts.csv', accounts, ['memberId','email','nickname','scenario','role','status','vu']),
            ('vu_accounts.csv', [r[:3] for r in accounts if r[-1]], ['memberId','email','nickname'])]:
            with open(temp/filename, 'w', newline='', encoding='utf-8') as f:
                writer = csv.writer(f, lineterminator='\n'); writer.writerow(header); writer.writerows(rows)
        scenarios = {'groups':{k:{'count':len(v),'sample_member_ids':v[:5]} for k,v in examples.items()},
            'matching_requests':[
                {'name':'basic','body':{'sameMajorOption':False},'expect':'opposite gender, matchable, no previous pair'},
                {'name':'mbti','body':{'importantOption':'MBTI','mbtiOption':'INTJ'},'expect':'candidate MBTI = INTJ'},
                {'name':'hobby','body':{'importantOption':'HOBBY','hobbyOption':'SPORTS'},'expect':'candidate has SPORTS hobby'},
                {'name':'contact','body':{'importantOption':'CONTACT','contactFrequency':'FREQUENT'},'expect':'candidate contact = FREQUENT'},
                {'name':'age','body':{'importantOption':'AGE','ageOption':'EQUAL'},'expect':'candidate age equals requester age'},
                {'name':'different_major','body':{'sameMajorOption':True},'expect':'candidate major differs'},
                {'name':'invalid_age_condition','body':{'importantOption':'AGE','ageOption':None},'expect':'NO_MATCHING_CANDIDATE; no committed item consumption'}],
            'notes':['Invalid request no_candidate is deterministic even with a large pool; valid-condition exhaustion requires a dedicated fixture.',
                     'Order/roulette/expiry dates are relative to as_of, not the future loading day.',
                     'All records are fixtures, not evidence that application workflows passed.']}
        if preset=='no-candidates':
            scenarios['matching_requests'].append({'name':'empty_pool','member_id':start_id+scenario_count,
                'body':{'sameMajorOption':False},'expect':'NO_MATCHING_CANDIDATE; all other profiles/candidates are unmatchable'})
        json_files = {'catalog_refs.json':refs, 'scenarios.json':scenarios,
                      'credentials.json':{'test_only':True, 'password':password, 'bcrypt':hashed, 'cost':10}}
        for name,obj in json_files.items():
            (temp/name).write_text(json.dumps(obj,ensure_ascii=False,indent=2)+'\n')
        manifest = {'version':VERSION,'dataset':dataset,'count':count,'scenario_count':scenario_count,
                    'vu_accounts':vu_accounts,'start_id':start_id,'end_id':start_id+count-1,
                    'seed':seed,'as_of':as_of,'at':at,'preset':preset,'timezone':'Asia/Seoul','distribution':distribution,
                    'tables':{t:columns(t) for t in TABLES},'counts':dict(w.counts),
                    'distributions':{k:dict(v) for k,v in distribution_counts.items()},
                    'files':{p.name:{'sha256':digest(p),'bytes':p.stat().st_size} for p in sorted(temp.iterdir())},
                    'application_sources':{str(p.relative_to(ROOT)):digest(p) for p in [
                        ROOT/'common-module/src/main/java/com/comatching/common/domain/enums/DefaultHobby.java',
                        ROOT/'common-module/src/main/java/com/comatching/common/domain/enums/ProfileTagItem.java',
                        ROOT/'common-module/src/main/java/com/comatching/common/domain/vo/KoreanAge.java',
                        ROOT/'matching-service/src/main/java/com/comatching/matching/domain/entity/MatchingCandidate.java']}}
        (temp/'manifest.json').write_text(json.dumps(manifest,ensure_ascii=False,indent=2)+'\n')
        for p in temp.iterdir(): p.chmod(0o600)
        temp.chmod(0o700)
        temp.rename(out)
        return manifest
    except BaseException:
        w.close()
        shutil.rmtree(temp)
        raise

def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--out', required=True)
    p.add_argument('--count', type=int, default=100000)
    p.add_argument('--scenario-count', type=int, default=1000)
    p.add_argument('--vu-accounts', type=int, default=500)
    p.add_argument('--start-id', type=int, default=1000001)
    p.add_argument('--seed', type=int, default=20261118)
    p.add_argument('--as-of', required=True, help='Asia/Seoul YYYY-MM-DD')
    p.add_argument('--at',default='12:00:00',help='Reference time in Asia/Seoul, HH:MM:SS')
    p.add_argument('--preset',choices=['baseline','no-candidates'],default='baseline')
    p.add_argument('--dataset', default='local-100k')
    p.add_argument('--distribution', choices=['uniform','skewed'], default='uniform')
    p.add_argument('--history-count', type=int)
    p.add_argument('--order-count', type=int)
    p.add_argument('--roulette-count', type=int)
    p.add_argument('--messages-per-room', type=int, default=20)
    args = vars(p.parse_args())
    args['password'] = os.environ.get('SEED_TEST_PASSWORD','LocalSeed!2026')
    m = generate(**args)
    print(json.dumps({'dataset':m['dataset'],'counts':m['counts'],'database_connected':False}, ensure_ascii=False,indent=2))

if __name__ == '__main__': main()
